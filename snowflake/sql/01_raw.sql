-- Raw layer: landing stage, file format and raw tables. Files are uploaded with PUT
-- by scripts/snowflake-build.mjs, then loaded with COPY INTO (02_load.sql).
USE ROLE MATERIALS_ENGINEER;
USE WAREHOUSE MATERIALS_WH;
USE DATABASE MATERIALS_AI;

CREATE SCHEMA IF NOT EXISTS RAW COMMENT = 'Data as delivered';
CREATE SCHEMA IF NOT EXISTS CURATED COMMENT = 'Parsed and typed records';
CREATE SCHEMA IF NOT EXISTS MART COMMENT = 'Data products for the API and BI';
CREATE SCHEMA IF NOT EXISTS SEARCH COMMENT = 'Chunks and Cortex Search service';
CREATE SCHEMA IF NOT EXISTS ML COMMENT = 'Snowflake ML models and evaluation';
CREATE SCHEMA IF NOT EXISTS APP COMMENT = 'Read models consumed by the copilot API';

CREATE OR REPLACE FILE FORMAT RAW.CSV_FF
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' ENCODING = 'UTF8' NULL_IF = ('') TRIM_SPACE = TRUE;

CREATE STAGE IF NOT EXISTS RAW.LANDING FILE_FORMAT = RAW.CSV_FF COMMENT = 'Landing zone for CSV files';

CREATE OR REPLACE TABLE RAW.AXLE_TESTS_RAW (
  ROW_NUMBER NUMBER, TESTING_GROUP STRING, MATERIAL STRING,
  C_PCT FLOAT, SI_PCT FLOAT, MN_PCT FLOAT, P_PCT FLOAT, S_PCT FLOAT, CR_PCT FLOAT, NI_PCT FLOAT,
  DIE_CASTING STRING, HARDENING_QUENCHING STRING, SAMPLES NUMBER,
  SERIES_TEMPERING STRING, ADDITIONAL_TEMPERING STRING, DIAMETER STRING,
  HV10_MEAN FLOAT, HV10_MIN FLOAT, HV10_MAX FLOAT,
  BEND_AVG_N FLOAT, BEND_MIN_N FLOAT, BEND_MAX_N FLOAT,
  DUCTILITY_PCT FLOAT, BRITTLENESS_PCT FLOAT,
  SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ
) COMMENT = '385,000 axle test records, one row per tested sample';

CREATE OR REPLACE TABLE RAW.SEM_PREDICTIONS_RAW (
  IMAGE_NAME STRING, DUCTILE_PCT FLOAT, BRITTLE_PCT FLOAT, DUCTILE_PIXELS NUMBER, BRITTLE_PIXELS NUMBER,
  SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ
) COMMENT = 'U-Net (ResNet50 encoder) ductile / brittle segmentation of SEM fracture images';

CREATE OR REPLACE TABLE RAW.NCR_RAW (
  NCR_ID STRING, OPENED_ON DATE, ROUTE_KEY STRING, PART STRING, STATUS STRING, DESCRIPTION STRING,
  SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ
) CHANGE_TRACKING = TRUE COMMENT = 'Nonconformance reports (illustrative texts written for the demo)';

CREATE OR REPLACE TABLE RAW.DOCUMENTS_RAW (
  DOC_ID STRING, TITLE STRING, CATEGORY STRING, BODY STRING, LOADED_AT TIMESTAMP_LTZ
) COMMENT = 'Procedures and guides written for the demo (markdown)';
