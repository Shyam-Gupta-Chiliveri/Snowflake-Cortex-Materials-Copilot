-- Curated layer and data products as dynamic tables: Snowflake keeps them in sync
-- with the raw tables. Parsing rules match scripts/lib/parse.mjs.
USE ROLE MATERIALS_ENGINEER;
USE WAREHOUSE MATERIALS_WH;
USE DATABASE MATERIALS_AI;

CREATE OR REPLACE DYNAMIC TABLE CURATED.AXLE_TESTS
  TARGET_LAG = '1 day' WAREHOUSE = MATERIALS_WH REFRESH_MODE = AUTO
  COMMENT = 'Typed axle tests with parsed campaign, group, press and heat-treatment route'
AS
WITH p AS (
  SELECT
    ROW_NUMBER AS TEST_ID,
    TESTING_GROUP,
    TRY_TO_NUMBER(REGEXP_SUBSTR(TESTING_GROUP, 'Version-([0-9]+)', 1, 1, 'e', 1)) AS VERSION,
    REGEXP_SUBSTR(TESTING_GROUP, 'Group ([A-I])', 1, 1, 'e', 1) AS GROUP_CODE,
    UPPER(REGEXP_SUBSTR(TESTING_GROUP, '[(](Friulpress|Freund)[)]', 1, 1, 'e', 1)) AS PRESS,
    TRY_TO_NUMBER(REGEXP_SUBSTR(TESTING_GROUP, 'Sample ([0-9]+)', 1, 1, 'e', 1)) AS SAMPLE_NO,
    MATERIAL, C_PCT, SI_PCT, MN_PCT, P_PCT, S_PCT, CR_PCT, NI_PCT,
    DIE_CASTING = 'Yes' AS DIE_CAST,
    TRY_TO_NUMBER(REGEXP_SUBSTR(HARDENING_QUENCHING, '([0-9]{4})', 1, 1, 'e', 1)) AS HARDEN_TEMP_C,
    SAMPLES,
    SERIES_TEMPERING AS SERIES_TEMPER_RAW,
    SERIES_TEMPERING ILIKE 'vac%' AS VACUUM_HARDENED,
    SERIES_TEMPERING = 'Yes' AS SERIES_TEMPER_UNSPECIFIED,
    TRY_TO_NUMBER(REGEXP_SUBSTR(SERIES_TEMPERING, '([0-9]{3}) *°? *C', 1, 1, 'ie', 1)) AS SERIES_C,
    TRY_TO_NUMBER(REGEXP_SUBSTR(SERIES_TEMPERING, '([0-9]+) *h', 1, 1, 'ie', 1)) AS SERIES_H,
    ADDITIONAL_TEMPERING AS ADD_TEMPER_RAW,
    TRY_TO_NUMBER(REGEXP_SUBSTR(ADDITIONAL_TEMPERING, '([0-9]{3}) *°? *C', 1, 1, 'ie', 1)) AS ADD_C,
    TRY_TO_NUMBER(REGEXP_SUBSTR(ADDITIONAL_TEMPERING, '([0-9]+) *h', 1, 1, 'ie', 1)) AS ADD_H,
    IFF(DIAMETER ILIKE '%7.8%', 7.8, 8.0)::NUMBER(3, 1) AS DIAMETER_MM,
    HV10_MEAN, HV10_MIN, HV10_MAX, BEND_AVG_N, BEND_MIN_N, BEND_MAX_N, DUCTILITY_PCT, BRITTLENESS_PCT
  FROM RAW.AXLE_TESTS_RAW
), k AS (
  SELECT p.*,
    'V' || VERSION || IFF(GROUP_CODE IS NULL, '', '-' || GROUP_CODE) || IFF(PRESS IS NULL, '', '-' || PRESS) AS GROUP_KEY,
    CASE
      WHEN VACUUM_HARDENED THEN 'Vacuum hardening, ' || SERIES_C || ' °C'
      WHEN SERIES_TEMPER_UNSPECIFIED THEN 'Series temper (temperature not recorded)'
      WHEN SERIES_C IS NOT NULL THEN 'Series temper ' || SERIES_C || ' °C / ' || SERIES_H || ' h'
    END AS SERIES_PART
  FROM p
)
SELECT
  TEST_ID, TESTING_GROUP, VERSION, GROUP_CODE, PRESS, SAMPLE_NO, GROUP_KEY,
  GROUP_KEY || IFF(VACUUM_HARDENED AND ADD_C IS NOT NULL, '-RT', '') AS ROUTE_KEY,
  COALESCE(NULLIF(TRIM(COALESCE(SERIES_PART, '') || ' ' ||
    IFF(ADD_C IS NULL, '', IFF(SERIES_PART IS NULL, 'Temper ', '+ ') || ADD_C || ' °C / ' || ADD_H || ' h')), ''),
    'Untempered (as quenched)') AS ROUTE_LABEL,
  MATERIAL, C_PCT, SI_PCT, MN_PCT, P_PCT, S_PCT, CR_PCT, NI_PCT, DIE_CAST, HARDEN_TEMP_C, SAMPLES,
  SERIES_TEMPER_RAW, VACUUM_HARDENED, SERIES_TEMPER_UNSPECIFIED, SERIES_C, SERIES_H, ADD_TEMPER_RAW, ADD_C, ADD_H,
  DIAMETER_MM, HV10_MEAN, HV10_MIN, HV10_MAX, BEND_AVG_N, BEND_MIN_N, BEND_MAX_N, DUCTILITY_PCT, BRITTLENESS_PCT
FROM k;

CREATE OR REPLACE DYNAMIC TABLE MART.ROUTE_QUALITY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'Data product: quality by heat-treatment route'
AS
SELECT
  ROUTE_KEY, ANY_VALUE(GROUP_KEY) AS GROUP_KEY, ANY_VALUE(VERSION) AS VERSION, ANY_VALUE(GROUP_CODE) AS GROUP_CODE,
  ANY_VALUE(PRESS) AS PRESS, ANY_VALUE(ROUTE_LABEL) AS ROUTE_LABEL,
  ANY_VALUE(SERIES_C) AS SERIES_C, ANY_VALUE(SERIES_H) AS SERIES_H, ANY_VALUE(ADD_C) AS ADD_C, ANY_VALUE(ADD_H) AS ADD_H,
  BOOLOR_AGG(VACUUM_HARDENED) AS VACUUM,
  COUNT(*) AS TESTS,
  ROUND(AVG(HV10_MEAN), 2) AS HV10_MEAN, ROUND(STDDEV_SAMP(HV10_MEAN), 2) AS HV10_STD,
  ROUND(AVG(BEND_AVG_N), 2) AS BEND_MEAN, ROUND(STDDEV_SAMP(BEND_AVG_N), 2) AS BEND_STD,
  ROUND(AVG(DUCTILITY_PCT), 2) AS DUCT_MEAN, ROUND(STDDEV_SAMP(DUCTILITY_PCT), 2) AS DUCT_STD,
  ROUND(100 * COUNT_IF(DUCTILITY_PCT < 23) / COUNT(*), 2) AS LOW_DUCT_SHARE_PCT,
  ROUND(100 * COUNT_IF(MATERIAL = 'X46CrS13') / COUNT(*), 2) AS X46_SHARE_PCT,
  ROUND(100 * COUNT_IF(DIE_CAST) / COUNT(*), 2) AS DIE_CAST_SHARE_PCT,
  ROUND(100 * COUNT_IF(DIAMETER_MM = 7.8) / COUNT(*), 2) AS D78_SHARE_PCT,
  ROUND(100 * COUNT_IF(SAMPLES = 3) / COUNT(*), 2) AS THREE_SAMPLE_SHARE_PCT
FROM CURATED.AXLE_TESTS
GROUP BY ROUTE_KEY;

CREATE OR REPLACE DYNAMIC TABLE MART.FACTOR_EFFECTS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'Data product: effect of material, diameter, die-casting and sample count'
AS
SELECT 'material' AS FACTOR, MATERIAL AS LEVEL, COUNT(*) AS TESTS, ROUND(AVG(HV10_MEAN), 2) AS HV10_MEAN,
       ROUND(AVG(BEND_AVG_N), 2) AS BEND_MEAN, ROUND(AVG(DUCTILITY_PCT), 2) AS DUCT_MEAN
FROM CURATED.AXLE_TESTS GROUP BY MATERIAL
UNION ALL
SELECT 'diameter', IFF(DIAMETER_MM = 7.8, '7.8 mm', '8 mm'), COUNT(*), ROUND(AVG(HV10_MEAN), 2), ROUND(AVG(BEND_AVG_N), 2), ROUND(AVG(DUCTILITY_PCT), 2)
FROM CURATED.AXLE_TESTS GROUP BY 2
UNION ALL
SELECT 'dieCast', IFF(DIE_CAST, 'Yes', 'No'), COUNT(*), ROUND(AVG(HV10_MEAN), 2), ROUND(AVG(BEND_AVG_N), 2), ROUND(AVG(DUCTILITY_PCT), 2)
FROM CURATED.AXLE_TESTS GROUP BY 2
UNION ALL
SELECT 'samples', TO_VARCHAR(SAMPLES), COUNT(*), ROUND(AVG(HV10_MEAN), 2), ROUND(AVG(BEND_AVG_N), 2), ROUND(AVG(DUCTILITY_PCT), 2)
FROM CURATED.AXLE_TESTS GROUP BY 2;

CREATE OR REPLACE DYNAMIC TABLE MART.DUCTILITY_DRIVERS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'Data product: Pearson correlation of each variable with ductility'
AS
SELECT f.FEATURE, ROUND(f.R, 4) AS R_WITH_DUCTILITY FROM (
  SELECT 'C_PCT' AS FEATURE, CORR(C_PCT, DUCTILITY_PCT) AS R FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'SI_PCT', CORR(SI_PCT, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'MN_PCT', CORR(MN_PCT, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'P_PCT', CORR(P_PCT, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'S_PCT', CORR(S_PCT, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'CR_PCT', CORR(CR_PCT, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'NI_PCT', CORR(NI_PCT, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'HV10_MEAN', CORR(HV10_MEAN, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
  UNION ALL SELECT 'BEND_AVG_N', CORR(BEND_AVG_N, DUCTILITY_PCT) FROM CURATED.AXLE_TESTS
) f;

CREATE OR REPLACE DYNAMIC TABLE MART.TEMPERING_RESPONSE
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'Data product: linear response of ductility to tempering temperature (Version 6)'
AS
SELECT 'Version 6, additional temper 180 to 240 °C for 1 h' AS SCOPE, COUNT(*) AS TESTS,
       ROUND(REGR_SLOPE(DUCTILITY_PCT, ADD_C), 4) AS SLOPE_PCT_PER_C,
       ROUND(REGR_INTERCEPT(DUCTILITY_PCT, ADD_C), 2) AS INTERCEPT_PCT,
       ROUND(CORR(DUCTILITY_PCT, ADD_C), 4) AS R
FROM CURATED.AXLE_TESTS WHERE VERSION = 6 AND ADD_C IS NOT NULL;

CREATE OR REPLACE DYNAMIC TABLE MART.DATA_QUALITY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'Data product: data-quality checks from PR-HV10-BEND section 5'
AS
SELECT COUNT(*) AS TESTS,
       COUNT_IF(HV10_MIN > HV10_MEAN OR HV10_MAX < HV10_MEAN) AS HV_ORDER_VIOLATIONS,
       COUNT_IF(ABS(DUCTILITY_PCT + BRITTLENESS_PCT - 100) > 0.1) AS SUM_NOT_100
FROM CURATED.AXLE_TESTS;

CREATE OR REPLACE DYNAMIC TABLE CURATED.SEM_FRACTOGRAPHY
  TARGET_LAG = '1 day' WAREHOUSE = MATERIALS_WH REFRESH_MODE = AUTO
  COMMENT = 'SEM image predictions linked to process routes by parsing the file name'
AS
WITH s AS (
  SELECT IMAGE_NAME, DUCTILE_PCT, BRITTLE_PCT, DUCTILE_PIXELS, BRITTLE_PIXELS,
    TRY_TO_NUMBER(REGEXP_SUBSTR(IMAGE_NAME, 'Version-([0-9]+)', 1, 1, 'e', 1)) AS VERSION,
    REGEXP_SUBSTR(IMAGE_NAME, 'Group-([A-I])', 1, 1, 'e', 1) AS GROUP_CODE,
    TRY_TO_NUMBER(REGEXP_SUBSTR(IMAGE_NAME, '([0-9]{3})C', 1, 1, 'e', 1)) AS TEMP_C
  FROM RAW.SEM_PREDICTIONS_RAW
)
SELECT s.*,
  CASE
    WHEN IMAGE_NAME LIKE '%QUW23%' THEN NULL
    WHEN STARTSWITH(IMAGE_NAME, 'Group-F-240C') THEN 'V6-F'
    WHEN VERSION = 6 AND GROUP_CODE = 'B' AND IMAGE_NAME ILIKE '%friulpress%' THEN 'V6-B-FRIULPRESS'
    WHEN VERSION = 6 AND GROUP_CODE IS NOT NULL THEN 'V6-' || GROUP_CODE
    WHEN VERSION = 14 THEN IFF(IMAGE_NAME ILIKE '%retemper%', 'V14-RT', 'V14')
  END AS ROUTE_KEY,
  CASE
    WHEN IMAGE_NAME LIKE '%QUW23%' THEN 'other campaign (QUW23)'
    WHEN STARTSWITH(IMAGE_NAME, 'Group-F-240C') THEN 'inferred from group and temperature'
    WHEN VERSION = 6 AND GROUP_CODE IS NOT NULL THEN 'file name'
    WHEN VERSION = 14 THEN 'file name'
    WHEN VERSION = 11 THEN 'version 11 without group'
    ELSE 'unmapped'
  END AS MAPPING
FROM s;

CREATE OR REPLACE DYNAMIC TABLE MART.SEM_BY_ROUTE
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'Data product: SEM ductile area by route'
AS
SELECT ROUTE_KEY, COUNT(*) AS IMAGES, ROUND(AVG(DUCTILE_PCT), 2) AS SEM_DUCTILE_MEAN,
       ROUND(STDDEV_SAMP(DUCTILE_PCT), 2) AS SEM_DUCTILE_STD,
       ROUND(100 * COUNT_IF(DUCTILE_PCT < 50) / COUNT(*), 2) AS CLEAVAGE_DOMINATED_PCT
FROM CURATED.SEM_FRACTOGRAPHY WHERE ROUTE_KEY IS NOT NULL GROUP BY ROUTE_KEY;

CREATE OR REPLACE DYNAMIC TABLE MART.SEM_MAPPING
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'How many SEM images could be linked to a route'
AS
SELECT MAPPING, COUNT(*) AS IMAGES FROM CURATED.SEM_FRACTOGRAPHY GROUP BY MAPPING;
