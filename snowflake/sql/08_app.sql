-- App read models and rule-based anomalies. Snowflake ML ANOMALY_DETECTION /
-- FORECAST need a time index the source CSVs do not have; those stay a Target.
-- Release blocks, SEM/lab mismatches and open NCRs are the live anomaly product.
USE ROLE MATERIALS_ENGINEER;
USE WAREHOUSE MATERIALS_WH;
USE DATABASE MATERIALS_AI;

CREATE OR REPLACE DYNAMIC TABLE MART.ANOMALIES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = MATERIALS_WH REFRESH_MODE = FULL
  COMMENT = 'Data product: release blocks, SEM/lab mismatches, open NCRs'
AS
SELECT
  'REL-' || ROUTE_KEY AS ANOMALY_ID,
  'release-block' AS KIND,
  IFF(LOW_DUCT_SHARE_PCT >= 50, 'critical', 'major') AS SEVERITY,
  ROUTE_KEY,
  ROUTE_KEY || ' fails release criteria' AS TITLE,
  'mean ductility ' || DUCT_MEAN || ' %, HV10 ' || HV10_MEAN || ', low-duct share ' || LOW_DUCT_SHARE_PCT || ' %' AS DETAIL,
  OBJECT_CONSTRUCT('ductMean', DUCT_MEAN, 'hv10Mean', HV10_MEAN, 'lowDuctSharePct', LOW_DUCT_SHARE_PCT) AS METRICS
FROM MART.ROUTE_QUALITY
WHERE DUCT_MEAN < 30 OR HV10_MEAN < 600 OR LOW_DUCT_SHARE_PCT >= 5
UNION ALL
SELECT
  'SEM-' || s.ROUTE_KEY, 'sem-lab-mismatch', 'major', s.ROUTE_KEY,
  s.ROUTE_KEY || ' SEM cleavage vs lab ductility',
  'lab ductility ' || r.DUCT_MEAN || ' % but ' || s.CLEAVAGE_DOMINATED_PCT || ' % of SEM images are cleavage-dominated',
  OBJECT_CONSTRUCT('ductMean', r.DUCT_MEAN, 'semDuctileMean', s.SEM_DUCTILE_MEAN, 'cleavageDominatedPct', s.CLEAVAGE_DOMINATED_PCT)
FROM MART.SEM_BY_ROUTE s
JOIN MART.ROUTE_QUALITY r ON r.ROUTE_KEY = s.ROUTE_KEY
WHERE s.CLEAVAGE_DOMINATED_PCT >= 50 AND r.DUCT_MEAN >= 30
UNION ALL
SELECT
  n.NCR_ID, 'open-ncr', IFF(n.SEVERITY = 'Critical', 'critical', IFF(n.SEVERITY = 'Major', 'major', 'minor')),
  n.ROUTE_KEY, n.NCR_ID || ' is open', COALESCE(n.SUMMARY, n.DESCRIPTION),
  OBJECT_CONSTRUCT('status', n.STATUS, 'severity', n.SEVERITY, 'category', n.CATEGORY)
FROM CURATED.NCR_ENRICHED n
WHERE n.STATUS = 'Open';

CREATE OR REPLACE VIEW APP.V_GROUPS AS SELECT * FROM MART.ROUTE_QUALITY;
CREATE OR REPLACE VIEW APP.V_FACTORS AS SELECT * FROM MART.FACTOR_EFFECTS;
CREATE OR REPLACE VIEW APP.V_SEM AS SELECT * FROM MART.SEM_BY_ROUTE;
CREATE OR REPLACE VIEW APP.V_ANOMALIES AS SELECT * FROM MART.ANOMALIES;
CREATE OR REPLACE VIEW APP.V_NCRS AS SELECT * FROM CURATED.NCR_ENRICHED;
CREATE OR REPLACE VIEW APP.V_TEMPERING AS SELECT * FROM MART.TEMPERING_RESPONSE;
CREATE OR REPLACE VIEW APP.V_DATA_QUALITY AS SELECT * FROM MART.DATA_QUALITY;
