-- Machine learning in Snowflake: a classification model predicts the ductility band
-- from process and chemistry only (no hardness or bending inputs), so it can be used
-- before a part is made. Deterministic 10 % train and 10 % hold-out splits.
USE ROLE MATERIALS_ENGINEER;
USE WAREHOUSE MATERIALS_WH;
USE DATABASE MATERIALS_AI;

CREATE OR REPLACE VIEW ML.DUCTILITY_FEATURES AS
SELECT TEST_ID,
  MATERIAL, IFF(DIE_CAST, 'Yes', 'No') AS DIE_CAST, DIAMETER_MM::FLOAT AS DIAMETER_MM, SAMPLES::FLOAT AS SAMPLES,
  C_PCT, SI_PCT, MN_PCT, P_PCT, S_PCT, CR_PCT, NI_PCT,
  COALESCE(SERIES_C, 0)::FLOAT AS SERIES_C, COALESCE(SERIES_H, 0)::FLOAT AS SERIES_H,
  IFF(SERIES_TEMPER_UNSPECIFIED, 'Yes', 'No') AS SERIES_UNSPECIFIED, IFF(VACUUM_HARDENED, 'Yes', 'No') AS VACUUM,
  COALESCE(ADD_C, 0)::FLOAT AS ADD_C, COALESCE(ADD_H, 0)::FLOAT AS ADD_H,
  CASE WHEN DUCTILITY_PCT < 23 THEN 'LOW' WHEN DUCTILITY_PCT < 31 THEN 'MEDIUM' ELSE 'HIGH' END AS DUCTILITY_BAND
FROM CURATED.AXLE_TESTS;

CREATE OR REPLACE TABLE ML.DUCTILITY_TRAIN AS SELECT * EXCLUDE TEST_ID FROM ML.DUCTILITY_FEATURES WHERE MOD(TEST_ID, 10) = 0;
CREATE OR REPLACE TABLE ML.DUCTILITY_HOLDOUT AS SELECT * EXCLUDE TEST_ID FROM ML.DUCTILITY_FEATURES WHERE MOD(TEST_ID, 10) = 5;

CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION ML.DUCTILITY_CLASSIFIER(
  INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'ML.DUCTILITY_TRAIN'),
  TARGET_COLNAME => 'DUCTILITY_BAND',
  CONFIG_OBJECT => {'evaluate': TRUE, 'on_error': 'skip'}
);

CALL ML.DUCTILITY_CLASSIFIER!SHOW_GLOBAL_EVALUATION_METRICS();
CREATE OR REPLACE TABLE ML.EVAL_METRICS AS SELECT * FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

CALL ML.DUCTILITY_CLASSIFIER!SHOW_FEATURE_IMPORTANCE();
CREATE OR REPLACE TABLE ML.FEATURE_IMPORTANCE AS SELECT * FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

CREATE OR REPLACE TABLE ML.HOLDOUT_PREDICTIONS AS
SELECT DUCTILITY_BAND,
  ML.DUCTILITY_CLASSIFIER!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
    'MATERIAL', MATERIAL, 'DIE_CAST', DIE_CAST, 'DIAMETER_MM', DIAMETER_MM, 'SAMPLES', SAMPLES,
    'C_PCT', C_PCT, 'SI_PCT', SI_PCT, 'MN_PCT', MN_PCT, 'P_PCT', P_PCT, 'S_PCT', S_PCT, 'CR_PCT', CR_PCT, 'NI_PCT', NI_PCT,
    'SERIES_C', SERIES_C, 'SERIES_H', SERIES_H, 'SERIES_UNSPECIFIED', SERIES_UNSPECIFIED, 'VACUUM', VACUUM,
    'ADD_C', ADD_C, 'ADD_H', ADD_H)):class::STRING AS PREDICTED
FROM ML.DUCTILITY_HOLDOUT;

CREATE OR REPLACE TABLE ML.HOLDOUT_METRICS AS
SELECT COUNT(*) AS ROWS_EVALUATED,
       ROUND(100 * COUNT_IF(PREDICTED = DUCTILITY_BAND) / COUNT(*), 2) AS ACCURACY_PCT,
       ROUND(100 * COUNT_IF(DUCTILITY_BAND = 'LOW' AND PREDICTED = 'LOW') / NULLIF(COUNT_IF(DUCTILITY_BAND = 'LOW'), 0), 2) AS LOW_RECALL_PCT
FROM ML.HOLDOUT_PREDICTIONS;
