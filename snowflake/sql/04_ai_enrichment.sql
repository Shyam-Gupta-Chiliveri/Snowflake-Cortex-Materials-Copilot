-- AI enrichment inside the pipeline: a stream captures new NCRs, a task classifies and
-- summarises them with Cortex LLM functions and merges them into CURATED.NCR_ENRICHED.
USE ROLE MATERIALS_ENGINEER;
USE WAREHOUSE MATERIALS_WH;
USE DATABASE MATERIALS_AI;

CREATE OR REPLACE TABLE CURATED.NCR_ENRICHED (
  NCR_ID STRING, OPENED_ON DATE, ROUTE_KEY STRING, PART STRING, STATUS STRING, DESCRIPTION STRING,
  CATEGORY STRING, SEVERITY STRING, SUMMARY STRING, ENRICHED_BY STRING, ENRICHED_AT TIMESTAMP_LTZ
) COMMENT = 'NCRs with root-cause area, severity and summary from Cortex';

CREATE OR REPLACE STREAM RAW.NCR_STREAM ON TABLE RAW.NCR_RAW SHOW_INITIAL_ROWS = TRUE;

CREATE OR REPLACE TASK CURATED.ENRICH_NCR
  WAREHOUSE = MATERIALS_WH SCHEDULE = '60 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('RAW.NCR_STREAM')
AS
MERGE INTO CURATED.NCR_ENRICHED t
USING (
  SELECT NCR_ID, OPENED_ON, ROUTE_KEY, PART, STATUS, DESCRIPTION,
    SNOWFLAKE.CORTEX.CLASSIFY_TEXT(DESCRIPTION,
      ['Heat treatment', 'Material chemistry', 'Geometry or machining', 'Die-casting or assembly', 'Testing or measurement'],
      {'task_description': 'Root-cause area of a nonconformance report for heat-treated stainless steel axles'}):label::STRING AS CATEGORY,
    SNOWFLAKE.CORTEX.CLASSIFY_TEXT(DESCRIPTION, ['Critical', 'Major', 'Minor'],
      {'task_description': 'Severity: Critical if a customer or field failure is involved, Major if parts are blocked or a process change is needed, Minor otherwise'}):label::STRING AS SEVERITY,
    SNOWFLAKE.CORTEX.SUMMARIZE(DESCRIPTION) AS SUMMARY
  FROM RAW.NCR_STREAM
  WHERE METADATA$ACTION = 'INSERT'
) s ON t.NCR_ID = s.NCR_ID
WHEN MATCHED THEN UPDATE SET OPENED_ON = s.OPENED_ON, ROUTE_KEY = s.ROUTE_KEY, PART = s.PART, STATUS = s.STATUS,
  DESCRIPTION = s.DESCRIPTION, CATEGORY = s.CATEGORY, SEVERITY = s.SEVERITY, SUMMARY = s.SUMMARY,
  ENRICHED_BY = 'Cortex CLASSIFY_TEXT + SUMMARIZE', ENRICHED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (NCR_ID, OPENED_ON, ROUTE_KEY, PART, STATUS, DESCRIPTION, CATEGORY, SEVERITY, SUMMARY, ENRICHED_BY, ENRICHED_AT)
  VALUES (s.NCR_ID, s.OPENED_ON, s.ROUTE_KEY, s.PART, s.STATUS, s.DESCRIPTION, s.CATEGORY, s.SEVERITY, s.SUMMARY,
          'Cortex CLASSIFY_TEXT + SUMMARIZE', CURRENT_TIMESTAMP());

ALTER TASK CURATED.ENRICH_NCR RESUME;
EXECUTE TASK CURATED.ENRICH_NCR;
