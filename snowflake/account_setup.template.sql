-- Run once in a Snowsight worksheet as ACCOUNTADMIN.
-- Creates two roles, an extra-small warehouse with a credit cap, the database, and two
-- service users that sign in with RSA key pairs (no passwords):
--   MATERIALS_LOADER_SVC  role MATERIALS_ENGINEER  builds the pipeline from a laptop
--   MATERIALS_APP_SVC     role MATERIALS_APP       read-only, used by the public API
-- `npm run snowflake:keys` fills in the two public keys below.

USE ROLE ACCOUNTADMIN;

-- Lets Cortex call models hosted in other regions when a model is not in this region.
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

CREATE ROLE IF NOT EXISTS MATERIALS_ENGINEER COMMENT = 'Owns the materials AI pipeline';
CREATE ROLE IF NOT EXISTS MATERIALS_APP COMMENT = 'Read-only access for the copilot API';
GRANT ROLE MATERIALS_APP TO ROLE MATERIALS_ENGINEER;
GRANT ROLE MATERIALS_ENGINEER TO ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS MATERIALS_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Materials copilot: pipeline, search and API queries';

CREATE RESOURCE MONITOR IF NOT EXISTS MATERIALS_RM WITH CREDIT_QUOTA = 25 FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE MATERIALS_WH SET RESOURCE_MONITOR = MATERIALS_RM;

GRANT USAGE, OPERATE ON WAREHOUSE MATERIALS_WH TO ROLE MATERIALS_ENGINEER;
GRANT USAGE ON WAREHOUSE MATERIALS_WH TO ROLE MATERIALS_APP;

CREATE DATABASE IF NOT EXISTS MATERIALS_AI COMMENT = '4Cr13 axle tests, SEM fractography, NCRs and procedures';
GRANT OWNERSHIP ON DATABASE MATERIALS_AI TO ROLE MATERIALS_ENGINEER COPY CURRENT GRANTS;

GRANT EXECUTE TASK ON ACCOUNT TO ROLE MATERIALS_ENGINEER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE MATERIALS_ENGINEER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE MATERIALS_APP;

CREATE USER IF NOT EXISTS MATERIALS_LOADER_SVC
  TYPE = SERVICE DEFAULT_ROLE = MATERIALS_ENGINEER DEFAULT_WAREHOUSE = MATERIALS_WH
  RSA_PUBLIC_KEY = '{{LOADER_PUBLIC_KEY}}'
  COMMENT = 'Builds the materials AI pipeline (key-pair auth)';
CREATE USER IF NOT EXISTS MATERIALS_APP_SVC
  TYPE = SERVICE DEFAULT_ROLE = MATERIALS_APP DEFAULT_WAREHOUSE = MATERIALS_WH
  RSA_PUBLIC_KEY = '{{APP_PUBLIC_KEY}}'
  COMMENT = 'Read-only copilot API (key-pair auth)';
GRANT ROLE MATERIALS_ENGINEER TO USER MATERIALS_LOADER_SVC;
GRANT ROLE MATERIALS_APP TO USER MATERIALS_APP_SVC;

-- Check: both users should show TYPE = SERVICE and HAS_RSA_PUBLIC_KEY = true.
SHOW USERS LIKE 'MATERIALS_%_SVC';
